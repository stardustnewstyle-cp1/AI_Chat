class DummyModelClient:
    """
    Intent / Level に応じてローカルで技術回答を生成する簡易モデル。
    TeacherLayer が構造化しやすい形式で返す。
    """

    def __init__(self):
        pass

    def generate(self, prompt: str, intent: str = "explain", level: str = "初級") -> str:

        # -------------------------
        # Intent: explain（説明）
        # -------------------------
        if intent == "explain":
            return (
                "【背景】\n"
                "この技術要素の基本的な仕組みと目的を整理します。\n\n"

                "【要点】\n"
                "・どんな問題を解決する技術か\n"
                "・内部構造や動作の概要\n"
                "・関連する概念\n\n"

                "【例】\n"
                "理解を助けるための簡単なコード例や具体例を示します。\n\n"

                "【注意点】\n"
                "・前提の違いで誤解が生じやすい\n"
                "・専門用語の使いすぎに注意\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: compare（比較）
        # -------------------------
        if intent == "compare":
            return (
                "【背景】\n"
                "複数の技術要素の違いを整理し、使い分けを明確にします。\n\n"

                "【構造の違い】\n"
                "・内部構造や設計思想の差\n"
                "・型システムや実行モデルの違い\n\n"

                "【例】\n"
                "Python と JavaScript のクラス構造の比較例を示します。\n"
                "Python は class ベース、JavaScript は prototype ベースです。\n\n"

                "【注意点】\n"
                "・用途によって優劣は変わる\n"
                "・バージョン差異に注意\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: design（設計）
        # -------------------------
        if intent == "design":
            return (
                "【背景】\n"
                "この設計課題の目的と前提を整理します。\n\n"

                "【設計方針】\n"
                "・責務分離\n"
                "・拡張性と保守性\n"
                "・依存関係の最小化\n\n"

                "【例】\n"
                "設計の良い例・悪い例を示し、改善ポイントを説明します。\n\n"

                "【注意点】\n"
                "・過剰設計を避ける\n"
                "・将来の変更を見据える\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: steps（手順）
        # -------------------------
        if intent == "steps":
            return (
                "【背景】\n"
                "この操作や実装を行うための前提を整理します。\n\n"

                "【手順】\n"
                "1. 必要なモジュールや環境を準備\n"
                "2. 基本構造を定義\n"
                "3. 実装を追加\n"
                "4. 動作確認\n\n"

                "【例】\n"
                "手順に沿った簡単なコード例を示します。\n\n"

                "【注意点】\n"
                "・順番を間違えるとエラーになる\n"
                "・依存関係に注意\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: improvement（改善）
        # -------------------------
        if intent == "improvement":
            return (
                "【背景】\n"
                "既存のコードや設計の改善点を整理します。\n\n"

                "【改善ポイント】\n"
                "・責務分離\n"
                "・冗長な処理の削減\n"
                "・命名の改善\n"
                "・パフォーマンス向上\n\n"

                "【例】\n"
                "改善前と改善後のコード例を示し、何が良くなったかを説明します。\n\n"

                "【注意点】\n"
                "・変更による副作用に注意\n"
                "・テストを必ず行う\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: summary（要約）
        # -------------------------
        if intent == "summary":
            return (
                "【背景】\n"
                "この内容の要点を簡潔にまとめます。\n\n"

                "【要点まとめ】\n"
                "・重要なポイント\n"
                "・押さえるべき概念\n"
                "・関連する技術要素\n\n"

                "【注意点】\n"
                "・詳細は省略されるため、前提の確認が必要\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: debug（デバッグ）
        # -------------------------
        if intent == "debug":
            return (
                "【背景】\n"
                "エラーや不具合の原因を特定するための観点を整理します。\n\n"

                "【確認ポイント】\n"
                "・エラーメッセージの内容\n"
                "・再現手順\n"
                "・依存関係や環境\n\n"

                "【例】\n"
                "典型的なエラー例とその原因を示します。\n\n"

                "【注意点】\n"
                "・複数の要因が絡む場合がある\n"
                "・ログを必ず確認する\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: optimization（最適化）
        # -------------------------
        if intent == "optimization":
            return (
                "【背景】\n"
                "パフォーマンス改善の目的と前提を整理します。\n\n"

                "【改善ポイント】\n"
                "・アルゴリズムの見直し\n"
                "・データ構造の最適化\n"
                "・I/O の削減\n"
                "・キャッシュの活用\n\n"

                "【例】\n"
                "改善前後の処理時間の比較例を示します。\n\n"

                "【注意点】\n"
                "・可読性とのバランス\n"
                "・過剰最適化を避ける\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # Intent: structuring（体系化）
        # -------------------------
        if intent == "structuring":
            return (
                "【背景】\n"
                "複雑な技術内容を体系的に整理します。\n\n"

                "【構造化ポイント】\n"
                "・概念の分類\n"
                "・関係性の整理\n"
                "・階層構造の明確化\n\n"

                "【例】\n"
                "体系化された図式や分類例を示します。\n\n"

                "【注意点】\n"
                "・分類基準を明確にする\n\n"

                f"【質問内容】\n{prompt}\n"
            )

        # -------------------------
        # デフォルト（explain）
        # -------------------------
        return (
            "【背景】\n"
            "この技術要素の基本的な仕組みと目的を整理します。\n\n"
            "【要点】\n"
            "・どんな問題を解決する技術か\n"
            "・内部構造や動作の概要\n\n"
            f"【質問内容】\n{prompt}\n"
        )
